// Понятные пользователю сообщения об ошибках базы данных

// Коды ошибок PostgreSQL и Node.js
const MESSAGES = {
  ECONNREFUSED: 'Нет соединения с базой данных: сервер базы данных остановлен или недоступен.',
  ENOTFOUND: 'Нет соединения с базой данных: сервер базы данных не найден.',
  ETIMEDOUT: 'База данных не отвечает. Повторите попытку позже.',
  '57P01': 'Сервер базы данных был остановлен во время обработки запроса.',
  '57P03': 'Сервер базы данных запускается. Повторите попытку через несколько секунд.',
  '08006': 'Соединение с базой данных было разорвано.',
  '28P01': 'Нет доступа к базе данных: неверное имя пользователя или пароль.',
  '3D000': 'База данных блога не найдена.',
  '42P01': 'В базе данных отсутствует нужная таблица.',
  '42501': 'Нет прав на чтение или запись данных в базе.',
  '55P03': 'Таблица базы данных заблокирована другим процессом. Повторите попытку позже.',
  '57014': 'Запрос к базе данных выполнялся слишком долго и был прерван.',
};

// Ошибки подключения без кода (тайм-аут пула, разрыв соединения)
function messageByText(text = '') {
  if (/timeout exceeded when trying to connect/i.test(text)) return MESSAGES.ETIMEDOUT;
  if (/Connection terminated/i.test(text)) return MESSAGES['08006'];
  return null;
}

function dbMessage(err) {
  if (!err) return null;
  const inner = err.errors?.[0] || err.cause;
  return (
    MESSAGES[err.code] ||
    messageByText(err.message) ||
    (inner && inner !== err ? dbMessage(inner) : null)
  );
}

module.exports = { dbMessage };
